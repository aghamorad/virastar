export const PRACTICAL_MODES = MODES.filter((m) => m.group === 'practical')
export const PLAYFUL_MODES = MODES.filter((m) => m.group === 'playful')

export function getMode(id: string): WritingMode {
  return MODES.find((m) => m.id === id) ?? MODES[0]
}
